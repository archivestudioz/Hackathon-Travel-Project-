let mediaCounter = 0;

/**
 * Builds a placeholder media set. The demo ships no imagery — every slot
 * renders a marked placeholder instead. Swap `provider` to "video" with a
 * `url`, or to "instagram"/"tiktok" with a canonical post URL, and the
 * renderer will use the real asset instead — no screen changes required.
 */
function placeholder(alt: string, count = 3): MediaAsset[] {
  return Array.from({ length: count }, (_, i) => ({
    id: `m${++mediaCounter}`,
    provider: "placeholder" as const,
    alt: i === 0 ? alt : `${alt} — view ${i + 1}`,
  }));
}

